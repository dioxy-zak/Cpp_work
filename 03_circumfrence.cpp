#include <iostream>
#define PI 3.14159
#define D1 17
#define D2 19
#define D3 21
int main() {
    std::cout << "Circumference of tire 1 = " << PI * D1 << std::endl;
    std::cout << "Circumference of tire 2 = " << PI * D2 << std::endl;
    std::cout << "Circumference of tire 3 = " << PI * D3 << std::endl;
    return 0;
}